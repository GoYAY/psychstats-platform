source("_common.R")
library(mclust)
set.seed(4204)
g <- sample(1:3,300,replace=TRUE,prob=c(0.4,0.35,0.25))
d <- cbind(stress=rnorm(300,c(-1,0.3,1.5)[g],0.6),support=rnorm(300,c(1,0.2,-1)[g],0.6),wellbeing=rnorm(300,c(1,0,-1.3)[g],0.6))
fit <- mclust::Mclust(d,G=1:4,modelNames=c("EEI","VVI"),verbose=FALSE)
stopifnot(all(is.finite(fit$parameters$mean)),fit$G>1)
print(summary(fit)); print(fit$BIC); print(fit$parameters$mean)
entropy <- 1+sum(fit$z*log(pmax(fit$z,1e-15)))/(nrow(d)*log(fit$G))
set.seed(4205)
restart <- mclust::Mclust(d,G=1:4,modelNames=c("EEI","VVI"),initialization=list(subset=sample(seq_len(nrow(d)),200)),verbose=FALSE)
stopifnot(is.finite(restart$bic))
same_structure <- as.numeric(restart$G==fit$G && restart$modelName==fit$modelName)
ari <- mclust::adjustedRandIndex(fit$classification,restart$classification)
print(summary(restart)); print(c(same_structure=same_structure,bic_gap=restart$bic-fit$bic,adjusted_rand=ari))
finish(c(k=fit$G,bic=fit$bic,entropy=entropy,mean_posterior=mean(apply(fit$z,1,max)),min_proportion=min(fit$parameters$pro),restart_same_structure=same_structure,restart_bic_gap=restart$bic-fit$bic,restart_ari=ari),list(profiles=data.frame(class=seq_len(fit$G),t(fit$parameters$mean)),posterior_summary=data.frame(class=seq_len(fit$G),expected_count=colSums(fit$z),assigned_count=as.numeric(table(factor(fit$classification,levels=seq_len(fit$G)))))))
