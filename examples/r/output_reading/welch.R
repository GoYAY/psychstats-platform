source("_common.R")
set.seed(4104)
d <- data.frame(group=factor(rep(c("A","B","C"),c(35,50,65))),score=c(rnorm(35,70,4),rnorm(50,73,12),rnorm(65,75,7)))
fit <- oneway.test(score~group,d,var.equal=FALSE); print(fit)
tab <- aggregate(score~group,d,function(x)c(n=length(x),mean=mean(x),sd=sd(x))); print(tab)
posthoc <- pairwise.t.test(d$score,d$group,pool.sd=FALSE,p.adjust.method="holm"); print(posthoc)
indices <- which(!is.na(posthoc$p.value),arr.ind=TRUE)
comparisons <- data.frame(group1=rownames(posthoc$p.value)[indices[,1]],group2=colnames(posthoc$p.value)[indices[,2]],p_holm=posthoc$p.value[indices])
finish(c(F=unname(fit$statistic),df1=unname(fit$parameter[1]),df2=unname(fit$parameter[2]),p=fit$p.value),list(pairwise_welch_holm=comparisons))
