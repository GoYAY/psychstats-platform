source("_common.R")
d <- read.csv("cross_sectional_survey.csv")
d$x <- d$stress-mean(d$stress); d$w <- d$social_support-mean(d$social_support)
fit <- lm(well_being~x*w,d); print(summary(fit))
v <- vcov(fit); coef <- coef(fit); values <- c(-sd(d$w),0,sd(d$w))
slopes <- sapply(values,function(w)coef["x"]+w*coef["x:w"])
ses <- sapply(values,function(w)sqrt(v["x","x"]+w*w*v["x:w","x:w"]+2*w*v["x","x:w"]))
tab <- data.frame(support_centered=values,slope=slopes,se=ses,ci_lower=slopes-qt(0.975,df.residual(fit))*ses,ci_upper=slopes+qt(0.975,df.residual(fit))*ses)
print(tab)
finish(c(interaction=unname(coef["x:w"]),p=coef(summary(fit))["x:w","Pr(>|t|)"],mean_slope=unname(slopes[2]),low_slope=unname(slopes[1]),high_slope=unname(slopes[3])),list(simple_slopes=tab,coefficients=data.frame(term=rownames(coef(summary(fit))),coef(summary(fit)),check.names=FALSE)))
