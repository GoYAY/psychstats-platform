source("_common.R")
library(nlme)
d <- read.csv("longitudinal_growth.csv")
d$treatment <- relevel(factor(d$treatment),"control")
print(table(d$treatment))
fit <- nlme::lme(outcome~time*treatment,d,random=list(id=nlme::pdDiag(~time)),method="ML",control=nlme::lmeControl(msMaxIter=200))
base <- update(fit,fixed=outcome~time+treatment)
print(summary(fit)); comparison <- anova(base,fit); print(comparison)
tab <- summary(fit)$tTable; target <- grep("^time:treatment",rownames(tab),value=TRUE); stopifnot(length(target)==1)
finish(c(interaction=tab[target,"Value"],p=tab[target,"p-value"],comparison_p=comparison$"p-value"[2],people=length(unique(d$id)),observations=nrow(d)),list(fixed=data.frame(term=rownames(tab),tab),comparison=data.frame(model=rownames(comparison),comparison)))
