source("_common.R")
set.seed(4205)
g <- sample(1:3,320,replace=TRUE,prob=c(0.4,0.35,0.25))
probs <- rbind(c(0.1,0.2,0.1,0.2,0.1),c(0.7,0.3,0.6,0.2,0.7),c(0.8,0.8,0.7,0.8,0.8))
d <- as.data.frame(sapply(1:5,function(j)1+rbinom(320,1,probs[g,j])))
names(d) <- paste0("q",1:5)
fits <- lapply(1:4,function(k) poLCA::poLCA(cbind(q1,q2,q3,q4,q5)~1,d,nclass=k,nrep=5,maxiter=1000,verbose=FALSE))
tab <- data.frame(k=1:4,bic=sapply(fits,function(m)m$bic),aic=sapply(fits,function(m)m$aic))
best <- which.min(tab$bic); fit <- fits[[best]]; stopifnot(fit$numiter<1000,length(fit$P)>1)
print(tab); print(fit)
conditional <- do.call(rbind,lapply(names(fit$probs),function(name)data.frame(item=name,class=seq_len(length(fit$P)),probability_response_2=fit$probs[[name]][,2])))
print(conditional)
entropy <- 1+sum(fit$posterior*log(pmax(fit$posterior,1e-15)))/(nrow(d)*log(length(fit$P)))
finish(c(k=length(fit$P),bic=fit$bic,entropy=entropy,min_proportion=min(fit$P),mean_posterior=mean(apply(fit$posterior,1,max))),list(candidates=tab,conditional_probabilities=conditional))
