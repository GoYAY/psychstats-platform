source("_common.R")
set.seed(4101)
a <- rbinom(90, 1, 0.22); b <- rbinom(100, 1, 0.32)
fit <- prop.test(c(sum(a),sum(b)),c(length(a),length(b)))
print(fit)
single <- binom.test(sum(a),length(a),p=0.20); print(single)
x <- rnorm(60,0,1); y <- rnorm(65,0,1.3)
v <- var.test(x,y); print(v)
finish(c(difference=mean(a)-mean(b),ci_lower=fit$conf.int[1],ci_upper=fit$conf.int[2],p=fit$p.value,variance_ratio=unname(v$estimate),variance_p=v$p.value,single_rate=mean(a),single_ci_lower=single$conf.int[1],single_ci_upper=single$conf.int[2]),list(single_proportion=data.frame(group="A",positive=sum(a),N=length(a),estimate=mean(a),ci_lower=single$conf.int[1],ci_upper=single$conf.int[2]),variance_comparison=data.frame(ratio=unname(v$estimate),df1=unname(v$parameter[1]),df2=unname(v$parameter[2]),ci_lower=v$conf.int[1],ci_upper=v$conf.int[2],p=v$p.value)))
