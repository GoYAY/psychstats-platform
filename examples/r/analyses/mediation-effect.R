source("examples/r/analyses/_common.R")
d <- read_data("cross_sectional_survey")
model_a <- lm(stress ~ social_support + age, data=d)
model_b <- lm(well_being ~ stress + social_support + age, data=d)
indirect <- unname(coef(model_a)["social_support"] * coef(model_b)["stress"])
set.seed(321)
boot <- replicate(300, {i <- sample.int(nrow(d),replace=TRUE); a <- coef(lm(stress ~ social_support + age,data=d[i,]))["social_support"]; b <- coef(lm(well_being ~ stress + social_support + age,data=d[i,]))["stress"]; a*b})
ci <- quantile(boot,c(.025,.975),na.rm=TRUE)
emit(c(indirect_effect=indirect, ci_lower=unname(ci[1]), ci_upper=unname(ci[2])))
