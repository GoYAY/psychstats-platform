K = 10
rows = []
recall = {1: 0, 3: 0, 5: 0, 10: 0}
mrr = 0.0
n = len(CASES)

for q, terms, cat in CASES:
    res = retrieve(q, k=K)
    first_rel = None
    marks = []
    for r in res:
        hit = any(t in r["text"] for t in terms)
        marks.append((r, hit))
        if hit and first_rel is None:
            first_rel = r["rank"]
    for kk in (1, 3, 5, 10):
        if first_rel is not None and first_rel <= kk:
            recall[kk] += 1
    if first_rel:
        mrr += 1.0 / first_rel

    print(f"\n[{cat}] Q: {q}")
    for r, hit in marks[:5]:
        flag = "HIT " if hit else "----"
        prev = r["text"][:58].replace("\n", " ")
        print(f"   {flag}#{r['rank']} p{r['page']} sec='{r['section']}' s={r['score']:.3f} | {prev}")
    print(f"   >> 首个相关 rank = {first_rel if first_rel else 'NONE(in top10)'}")

print("\n" + "=" * 60)
print(f"样本数 n = {n}")
for kk in (1, 3, 5, 10):
    print(f"Recall@{kk} = {recall[kk]}/{n} = {recall[kk]/n:.3f}")
print(f"MRR = {mrr/n:.3f}")
print(f"HitRate@10 = {recall[10]/n:.3f}")

# ---- 表格/数字噪声 chunk 占比（供 chunking 审计用）----
idx = load_index()
cjk = re.compile(r"[\u4e00-\u9fff]")
low = 0
for c in idx["chunks"]:
    t = c["text"]
    ratio = len(cjk.findall(t)) / max(len(t), 1)
    if ratio < 0.35:
        low += 1
print(f"\n[chunk 质量] 中文占比<35% 的 chunk（疑似表格/数字噪声）: {low}/{len(idx['chunks'])} = {low/len(idx['chunks']):.1%}")
